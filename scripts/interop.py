#!/usr/bin/env python3
"""Check both Rust -> MoonBit and MoonBit -> Rust binary interoperability.

Fixture embedding is generated test data, excluded from production LOC. It
keeps the test backend-independent and requires no filesystem or C/JS FFI in
the MoonBit library or in the harness. Equivalent FSTs need not be byte-identical.
"""
from __future__ import annotations

import argparse
from contextlib import contextmanager
import json
from pathlib import Path
import subprocess
import sys
from typing import Any

from oracle_common import ROOT, Oracle, load_cases

PREFIX = "MOONFST_INTEROP\t"


def bridge_source(cases: list[tuple[dict[str, Any], dict[str, Any], bytes]]) -> str:
    source = ["// @generated by scripts/interop.py. Test data only; DO NOT EDIT.\n"]
    blobs: list[str] = []

    def embed(value: str) -> str:
        number = len(blobs)
        blobs.append(value)
        return f"fixture_blob_{number}()"

    source += ["///|\nfn fixture_cases() -> Array[Fixture] {\n  [\n"]
    for case, expected, data in cases:
        encoded_entries = json.dumps(expected["entries"], separators=(",", ":"))
        source += ["    {\n",
                   "      name: " + json.dumps(case["name"]) + ",\n",
                   "      kind: " + json.dumps(case["kind"]) + ",\n",
                   "      data_hex: " + embed(data.hex()) + ",\n",
                   "      entries_json: " + embed(encoded_entries) + ",\n",
                   "    },\n"]
    source += ["  ]\n}\n"]
    for number, blob in enumerate(blobs):
        source += [f"\n///|\nfn fixture_blob_{number}() -> String {{\n",
                   "  let output = StringBuilder()\n"]
        for offset in range(0, len(blob), 4096):
            source.append("  output.write_string(" + json.dumps(blob[offset:offset + 4096]) + ")\n")
        source += ["  output.to_string()\n}\n"]
    return "".join(source)


@contextmanager
def embedded_cases(cases: list[tuple[dict[str, Any], dict[str, Any], bytes]]):
    """Restore the small tracked placeholder after every success or failure."""
    destination = ROOT / "src" / "integration" / "fixtures_generated.mbt"
    original = destination.read_bytes()
    try:
        destination.write_text(bridge_source(cases))
        yield
    finally:
        destination.write_bytes(original)


def run_moon(target: str) -> list[dict[str, Any]]:
    command = ["moon", "run", "src/integration", "--target", target, "--release", "--deny-warn"]
    result = subprocess.run(command, cwd=ROOT, text=True, encoding="utf-8", capture_output=True)
    if result.returncode:
        sys.stderr.write(result.stderr)
        sys.stderr.write(result.stdout[-12000:])
        raise RuntimeError(f"MoonBit {target} integration process failed ({result.returncode})")
    reports = []
    for line in result.stdout.splitlines():
        if line.startswith(PREFIX):
            reports.append(json.loads(line[len(PREFIX):]))
    if not reports:
        sys.stderr.write(result.stderr)
        raise RuntimeError(f"MoonBit {target} emitted no integration reports")
    return reports


def verify_report(case: dict[str, Any], expected: dict[str, Any], report: dict[str, Any], oracle: Oracle) -> None:
    name = case["name"]
    assert report.get("ok") is True, f"{name}: {report.get('error', report)}"
    records = expected["entries"]
    assert report["entries"] == records, f"{name}: Rust bytes decoded differently by MoonBit"
    assert int(report["len"]) == len(records), f"{name}: incorrect declared length"
    dictionary = dict(records)
    probes = ["", "00", "ff", "00010203", "ffffffffffffffff"]
    if records:
        probes += [records[0][0], records[len(records) // 2][0], records[-1][0]]
    assert report["lookups"] == [[key, dictionary.get(key)] for key in probes], f"{name}: lookup mismatch"
    assert report["range"] == [pair for pair in records if b"\0" <= bytes.fromhex(pair[0]) < b"\xff"], f"{name}: range mismatch"
    prefix = bytes.fromhex(report["prefix_hex"])
    assert report["prefix"] == [pair for pair in records if bytes.fromhex(pair[0]).startswith(prefix)], f"{name}: prefix mismatch"
    reference = oracle.request({
        "op": "read", "bytes_hex": report["moon_bytes_hex"], "lookups": probes,
        "range": {"ge": "00", "lt": "ff"}, "prefix": prefix.hex(),
    })
    assert reference["entries"] == records, f"{name}: Rust cannot recover the MoonBit builder's entries"
    assert reference["len"] == len(records), f"{name}: Rust sees incorrect MoonBit length"
    assert reference["lookups"] == report["lookups"], f"{name}: query mismatch across writers"
    assert reference["range"] == report["range"], f"{name}: range mismatch across writers"
    assert reference["prefix"] == report["prefix"], f"{name}: prefix mismatch across writers"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", action="append", choices=["native", "js", "wasm-gc", "wasm"],
                        help="Repeat for multiple backends; default: native.")
    parser.add_argument("--case", action="append", dest="names", help="Run selected fixture names only.")
    parser.add_argument("--generate-only", action="store_true", help="Write an inspectable .mbt.txt embedding without changing compiled sources.")
    args = parser.parse_args()
    _, cases = load_cases()
    if args.names:
        unknown = set(args.names) - {case["name"] for case, _, _ in cases}
        if unknown:
            parser.error("unknown fixtures: " + ", ".join(sorted(unknown)))
        cases = [case for case in cases if case[0]["name"] in args.names]
    if args.generate_only:
        (ROOT / "src" / "integration" / "fixtures_embedded.mbt.txt").write_text(bridge_source(cases))
        print(f"Wrote {len(cases)} fixtures to src/integration/fixtures_embedded.mbt.txt")
        return 0
    targets = args.target or ["native"]
    with Oracle() as oracle, embedded_cases(cases):
        for target in targets:
            reports = run_moon(target)
            by_name = {report["name"]: report for report in reports}
            assert len(reports) == len(by_name) == len(cases), f"{target}: missing or repeated reports"
            for case, expected, _ in cases:
                assert case["name"] in by_name, f"{target}: missing {case['name']}"
                verify_report(case, expected, by_name[case["name"]], oracle)
            print(f"{target}: {len(cases)} fixtures passed Rust -> MoonBit and MoonBit -> Rust, "
                  "including all records, u64 values, checksums, lookup, range and prefix queries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
